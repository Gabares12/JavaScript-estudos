let incremento = 5;
console.log(incremento++); // Saída: 5 (retorna o valor atual de i)
console.log(incremento);   // Saída: 6 (i foi incrementado após a execução)

let numeroOito = 8;
console.log(++numeroOito); // Saída: 9 (j foi incrementado antes de ser usado)
console.log(numeroOito);   // Saída: 9 (j já foi incrementado)